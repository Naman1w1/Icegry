export function byCollection(slug) {
  if (!slug || slug === "all" || slug === "all-products" || slug === "view-all") return products;
  if (slug === "new-in" || slug === "latest-drop") return products.slice(0, 36);
  if (slug === "featured") return products.slice(0, 12);
  if (slug === "polo") return products.filter((p) => p.cats && p.cats.includes("polos"));
  if (slug === "denims" || slug === "denim") return products.filter((p) => p.cats && (p.cats.includes("jeans") || p.cats.includes("denim")));
  if (slug === "puffer-jacket") return products.filter((p) => p.cats && (p.cats.includes("jackets") || p.cats.includes("puffer")));
  if (slug === "jersey") return products.filter((p) => p.cats && (p.cats.includes("jersey") || p.cats.includes("t-shirts")));
  if (slug === "crop-top") return products.filter((p) => p.cats && (p.cats.includes("crop") || p.cats.includes("tops")));
  if (slug === "sweatshirt") return products.filter((p) => p.cats && p.cats.includes("sweatshirts"));
  if (slug === "cargo") return products.filter((p) => p.cats && p.cats.includes("cargos"));
  return products.filter((p) => p.cats && p.cats.includes(slug));
}

